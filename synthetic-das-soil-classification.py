def estimate_vp_from_arrival(strain: np.ndarray, z: np.ndarray, dt: float) -> float:
    """Rough Vp estimate using picked arrival index vs depth.

    We pick the envelope peak index per channel, then fit t(z) = a*z + b.
    For a two-way model: t ~ 2*z/vp => vp ~ 2/a.

    This is intentionally simple/robust.
    """
    K, Nt = strain.shape
    if K < 4:
        return float("nan")

    # Use a smoothed envelope proxy to reduce noise.
    win = max(9, int(0.006 / dt))  # ~6 ms window
    picks = np.zeros(K, dtype=np.float64)

    for k in range(K):
        env = moving_rms(strain[k, :], win=win)
        # restrict search to avoid picking pure noise at the end
        search_end = int(max(16, 0.8 * Nt))
        idx = int(np.argmax(env[:search_end]))
        picks[k] = float(idx) * dt

    # Fit t = a*z + b
    zz = z.astype(np.float64)
    if np.allclose(zz, zz[0]):
        return float("nan")

    A = np.vstack([zz, np.ones_like(zz)]).T
    try:
        coeff, _, _, _ = np.linalg.lstsq(A, picks, rcond=None)
        a = float(coeff[0])
        if abs(a) <= 1e-12:
            return float("nan")
        vp_hat = 2.0 / a
        return float(vp_hat)
    except Exception:
        return float("nan")


def extract_features_one(strain: np.ndarray, z: np.ndarray, dt: float) -> Dict[str, float]:
    K, Nt = strain.shape

    # Aggregate trace: mean over channels (common for stable spectral features)
    trace_mean = np.mean(strain, axis=0).astype(np.float32)

    # Basic energy stats
    rms_all = float(np.sqrt(np.mean(strain.astype(np.float64) ** 2)))
    rms_trace = float(np.sqrt(np.mean(trace_mean.astype(np.float64) ** 2)))
    abs_mean = float(np.mean(np.abs(trace_mean)))
    abs_max = float(np.max(np.abs(trace_mean)))

    # Envelope stats on mean trace
    win = max(9, int(0.006 / dt))
    env = moving_rms(trace_mean, win=win)
    env_mean = float(np.mean(env))
    env_max = float(np.max(env))
    env_p95 = float(np.percentile(env, 95))

    # Spectral
    centroid, bw, rolloff, peak_hz = spectral_features(trace_mean, dt=dt)

    # Shape
    kurt = float(simple_kurtosis(trace_mean))
    skew = float(simple_skewness(trace_mean))

    # Physics-inspired
    vp_hat = float(estimate_vp_from_arrival(strain, z=z, dt=dt))

    # SNR proxy: envelope peak / envelope median
    env_med = float(np.median(env))
    snr_proxy = float(env_max / max(env_med, 1e-9))

    return {
        "rms_all": rms_all,
        "rms_trace": rms_trace,
        "abs_mean": abs_mean,
        "abs_max": abs_max,
        "env_mean": env_mean,
        "env_max": env_max,
        "env_p95": env_p95,
        "snr_proxy": snr_proxy,
        "spec_centroid_hz": float(centroid),
        "spec_bandwidth_hz": float(bw),
        "spec_rolloff_hz": float(rolloff),
        "spec_peak_hz": float(peak_hz),
        "kurtosis": kurt,
        "skewness": skew,
        "vp_hat": vp_hat,
    }


