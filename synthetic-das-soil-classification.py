def simulate_one_sample(soil_name: str, base_seed: int, sample_idx: int, params: SimParams) -> Tuple[np.ndarray, Dict[str, float]]:
    """Return (strain[K, Nt], metadata)."""
    rng = np.random.default_rng(int(base_seed) + 100000 * int(sample_idx) + 17)

    vp_mu = float(VEL_MAP_VP[soil_name])
    vp_sigma = float(VEL_SIGMA_VP.get(soil_name, 0.1 * vp_mu))

    vp = float(rng.normal(vp_mu, vp_sigma))
    vp = float(np.clip(vp, 0.3 * vp_mu, 3.0 * vp_mu))


    # Depth axis
    K = int(params.n_channels)
    z = np.linspace(0.0, float(params.z_max_m), K, dtype=np.float32)

    # Fast-time axis
    dt = float(params.dt_fast_s)
    Nt = int(params.n_fast)
    t = (np.arange(Nt, dtype=np.float32) * dt)

    # Per-sample variability
    amp0 = float(params.amp0) * float(rng.uniform(0.7, 1.3))
    noise_sigma = float(params.noise_sigma) * float(rng.uniform(0.6, 1.6))
    alpha = float(params.atten_alpha) * float(rng.uniform(0.6, 1.4))
    jitter = float(params.jitter_s) * float(rng.uniform(0.5, 1.5))

    # Pulse bandwidth / center frequency
    f0 = float(params.band_hz) * float(rng.uniform(0.7, 1.3))
    width = float(params.pulse_width_s) * float(rng.uniform(0.7, 1.3))

    strain = np.zeros((K, Nt), dtype=np.float32)

    # Two-way travel time (simple) + depth-dependent attenuation
    # t_arr(z) in seconds
    t_arr = (2.0 * z.astype(np.float64)) / max(vp, 1.0)

    for k in range(K):
        t0 = float(t_arr[k]) + float(rng.normal(0.0, jitter))
        a = amp0 * math.exp(-alpha * float(z[k]))
        sig = gaussian_pulse(t, t0, width, f0).astype(np.float32)

        # Add a small later reflection (optional) for realism
        if rng.random() < 0.35:
            t1 = t0 + float(rng.uniform(0.02, 0.09))
            a1 = a * float(rng.uniform(0.15, 0.45))
            sig = sig + (a1 * gaussian_pulse(t, t1, width * 1.2, f0 * 0.8).astype(np.float32))

        # Noise
        sig = sig + rng.normal(0.0, noise_sigma, size=Nt).astype(np.float32)
        strain[k, :] = sig

    meta = {
        "vp": vp,
        "amp0": amp0,
        "noise_sigma": noise_sigma,
        "atten_alpha": alpha,
        "pulse_f0_hz": f0,
        "pulse_width_s": width,
    }
    return strain, meta


