def build_dataset(
    class_names: List[str],
    samples_per_class: int,
    base_seed: int,
    sim_params: SimParams,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, List[Dict[str, float]]]:
    """Return X, y, z, meta_list."""
    rng = np.random.default_rng(int(base_seed))

    n_classes = len(class_names)
    n_total = int(samples_per_class) * n_classes

    K = int(sim_params.n_channels)
    Nt = int(sim_params.n_fast)
    z = np.linspace(0.0, float(sim_params.z_max_m), K, dtype=np.float32)

    X = np.zeros((n_total, K, Nt), dtype=np.float32)
    y = np.zeros((n_total,), dtype=np.int32)
    meta_list: List[Dict[str, float]] = []

    idx = 0
    for ci, soil in enumerate(class_names):
        for si in range(int(samples_per_class)):
            # vary per sample with deterministic seed based on class+index
            strain, meta = simulate_one_sample(
                soil_name=soil,
                base_seed=int(base_seed) + 1000 * ci,
                sample_idx=si,
                params=sim_params,
            )
            X[idx, :, :] = strain
            y[idx] = int(ci)
            meta_list.append(meta)
            idx += 1

    # Shuffle samples
    perm = rng.permutation(n_total)
    X = X[perm]
    y = y[perm]
    meta_list = [meta_list[i] for i in perm]

    return X, y, z, meta_list


def save_h5(out_path: str, X: np.ndarray, y: np.ndarray, z: np.ndarray, class_names: List[str], dt: float, meta_list: List[Dict[str, float]]) -> None:
    import h5py

    # Prepare meta arrays
    vp_arr = np.array([m.get("vp", np.nan) for m in meta_list], dtype=np.float32)
    amp0_arr = np.array([m.get("amp0", np.nan) for m in meta_list], dtype=np.float32)
    noise_arr = np.array([m.get("noise_sigma", np.nan) for m in meta_list], dtype=np.float32)
    atten_arr = np.array([m.get("atten_alpha", np.nan) for m in meta_list], dtype=np.float32)
    f0_arr = np.array([m.get("pulse_f0_hz", np.nan) for m in meta_list], dtype=np.float32)
    w_arr = np.array([m.get("pulse_width_s", np.nan) for m in meta_list], dtype=np.float32)

    with h5py.File(out_path, "w") as f:
        f.create_dataset("X", data=X, compression="gzip", compression_opts=4)
        f.create_dataset("y", data=y)
        f.create_dataset("z", data=z)
        f.create_dataset("dt_fast_s", data=np.array([dt], dtype=np.float32))

        # class names as UTF-8 strings (future-proof for accents)
        dt_str = h5py.string_dtype(encoding="utf-8")
        f.create_dataset("class_names", data=np.array(class_names, dtype=dt_str))

        g = f.create_group("meta")
        g.create_dataset("vp", data=vp_arr)
        g.create_dataset("amp0", data=amp0_arr)
        g.create_dataset("noise_sigma", data=noise_arr)
        g.create_dataset("atten_alpha", data=atten_arr)
        g.create_dataset("pulse_f0_hz", data=f0_arr)
        g.create_dataset("pulse_width_s", data=w_arr)


def train_and_evaluate(
    features_csv: str,
    metrics_json: str,
    cm_png: str,
    class_names: List[str],
    seed: int,
    drop_cols: List[str] = None,
    model_out_path: str = None,
) -> None:
    import pandas as pd
    from sklearn.model_selection import train_test_split
    from sklearn.preprocessing import StandardScaler
    from sklearn.pipeline import Pipeline
    from sklearn.linear_model import LogisticRegression
    from sklearn.ensemble import HistGradientBoostingClassifier
    from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix

    df = pd.read_csv(features_csv)

    # Optional: drop columns that can leak ground-truth or are not intended as inputs.
    if drop_cols:
        for c in drop_cols:
            if c in df.columns:
                df = df.drop(columns=[c])

    y = df["label_id"].values.astype(int)
    X = df.drop(columns=["label_id", "label_name"]).values

    # Robust split: stratified split needs at least 2 samples per class in the test set.
    n_samples = int(X.shape[0])
    n_classes = int(len(class_names))
    desired_test = max(1, int(round(0.20 * n_samples)))
    min_test = 2 * n_classes
    test_n = max(desired_test, min_test)
    if test_n >= n_samples:
        # Too small to split properly; skip ML gracefully.
        payload = {
            "best_model": None,
            "results": {},
            "seed": int(seed),
            "n_classes": n_classes,
            "n_features": int(X.shape[1]),
            "n_samples": n_samples,
            "warning": "Dataset too small for stratified train/test split; ML step skipped.",
        }
        with open(metrics_json, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)
        return

    test_size = float(test_n) / float(n_samples)

    Xtr, Xte, ytr, yte = train_test_split(
        X,
        y,
        test_size=test_size,
        random_state=int(seed),
        stratify=y,
    )

    models = {}

    # Model 1: Logistic Regression (scaled)
    models["logreg"] = Pipeline(
        steps=[
            ("scaler", StandardScaler()),
            (
                "clf",
                LogisticRegression(
                    max_iter=2000,
                    solver="lbfgs",
                    random_state=int(seed),
                ),
            ),
        ]
    )

    # Model 2: HistGradientBoosting (no scaling needed)
    models["hgb"] = HistGradientBoostingClassifier(
        random_state=int(seed),
        max_depth=6,
        learning_rate=0.08,
        max_iter=250,
    )

    results = {}
    best_name = None
    best_score = -1.0

    best_model = None
    for name, model in models.items():
        model.fit(Xtr, ytr)
        pred = model.predict(Xte)
        acc = float(accuracy_score(yte, pred))
        f1m = float(f1_score(yte, pred, average="macro"))
        rep = classification_report(yte, pred, target_names=class_names, output_dict=True, zero_division=0)
        cm = confusion_matrix(yte, pred, labels=list(range(len(class_names))))

        results[name] = {
            "accuracy": acc,
            "f1_macro": f1m,
            "classification_report": rep,
            "confusion_matrix": cm.tolist(),
        }

        if f1m > best_score:
            best_score = f1m
            best_name = name
            best_model = model

    assert best_name is not None

    # Save confusion plot for best
    cm_best = np.array(results[best_name]["confusion_matrix"], dtype=int)
    plot_confusion(cm_best, class_names, cm_png, title=f"Confusion Matrix (best={best_name})")

    payload = {
        "best_model": best_name,
        "results": results,
        "seed": int(seed),
        "n_classes": int(len(class_names)),
        "n_features": int(X.shape[1]),
        "n_samples": int(X.shape[0]),
    }

    with open(metrics_json, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)

    # Optional: persist best model for reproducibility.
    if model_out_path and best_model is not None:
        try:
            import joblib

            joblib.dump(best_model, model_out_path)
        except Exception as e:
            # Do not fail the run if joblib is missing.
            print(f"[WARN] Could not save model to {model_out_path}: {e}")


