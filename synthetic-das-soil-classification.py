def sync_latest(run_dir: str, latest_dir: str) -> None:
    """Overwrite latest/ with the contents of run_dir."""
    hard_reset_dir(latest_dir)
    # copytree requires dest not to exist; we already created it.
    for name in os.listdir(run_dir):
        src = os.path.join(run_dir, name)
        dst = os.path.join(latest_dir, name)
        if os.path.isdir(src):
            shutil.copytree(src, dst)
        else:
            shutil.copy2(src, dst)


