def gaussian_pulse(t: np.ndarray, t0: float, width: float, f0: float) -> np.ndarray:
    """Gaussian-modulated cosine pulse."""
    # width is standard deviation (s)
    x = (t - t0) / max(width, 1e-9)
    env = np.exp(-0.5 * x * x)
    return env * np.cos(2.0 * math.pi * f0 * (t - t0))


def moving_rms(x: np.ndarray, win: int) -> np.ndarray:
    """Envelope proxy: sqrt(moving average of x^2)."""
    win = int(max(3, win))
    if win % 2 == 0:
        win += 1
    kernel = np.ones(win, dtype=np.float32) / float(win)
    x2 = (x.astype(np.float32) ** 2)
    y = np.convolve(x2, kernel, mode="same")
    return np.sqrt(np.maximum(y, 0.0))


def spectral_features(x: np.ndarray, dt: float) -> Tuple[float, float, float, float]:
    """Return (centroid_hz, bandwidth_hz, rolloff_hz, peak_hz) from rFFT."""
    x = x.astype(np.float64)
    n = x.size
    if n < 8:
        return 0.0, 0.0, 0.0, 0.0

    # remove DC
    x = x - float(np.mean(x))
    X = np.fft.rfft(x)
    P = (np.abs(X) ** 2)
    freqs = np.fft.rfftfreq(n, d=dt)

    psum = float(np.sum(P))
    if psum <= 1e-12:
        return 0.0, 0.0, 0.0, 0.0

    centroid = float(np.sum(freqs * P) / psum)
    bandwidth = float(np.sqrt(np.sum(((freqs - centroid) ** 2) * P) / psum))

    # rolloff: frequency below which 85% of energy lies
    cumsum = np.cumsum(P)
    thr = 0.85 * cumsum[-1]
    idx = int(np.searchsorted(cumsum, thr))
    idx = int(np.clip(idx, 0, freqs.size - 1))
    rolloff = float(freqs[idx])

    peak_idx = int(np.argmax(P))
    peak_hz = float(freqs[peak_idx])

    return centroid, bandwidth, rolloff, peak_hz


def simple_kurtosis(x: np.ndarray) -> float:
    x = x.astype(np.float64)
    mu = float(np.mean(x))
    v = float(np.mean((x - mu) ** 2))
    if v <= 1e-12:
        return 0.0
    m4 = float(np.mean((x - mu) ** 4))
    return m4 / (v * v)


def simple_skewness(x: np.ndarray) -> float:
    x = x.astype(np.float64)
    mu = float(np.mean(x))
    s = float(np.std(x))
    if s <= 1e-12:
        return 0.0
    m3 = float(np.mean((x - mu) ** 3))
    return m3 / (s ** 3)


